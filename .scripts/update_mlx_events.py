"""Write the ML+Coffee schedule include from the UW-Madison events calendar.

Reads events tagged "ML+X" from today.wisc.edu's JSON API, keeps the ML+Coffee
sessions, and writes includes/_mlx-coffee-events.qmd: the next session and a
table of past sessions since May 2025, each linked to its calendar entry. The About ML+X
page includes that file. The file is rewritten only when its content changes.

    python3 .scripts/update_mlx_events.py                 # fetch and write
    python3 .scripts/update_mlx_events.py --from-file x.json   # parse a saved response instead (for testing)

Event fields, per UW's own calendar plugin (UWMadisonUcomm/uwmadison_events-wp):
id, title, subtitle, description, startDate, endDate. An event's page is
https://today.wisc.edu/events/view/<id>.
"""
import datetime as dt
import json
import re
import sys
import urllib.parse
import urllib.request

API = "https://today.wisc.edu/events/tag/{tag}.json"
TAG = "ML+X"
OUT = "includes/_mlx-coffee-events.qmd"
TAG_PAGE = "https://today.wisc.edu/events/tag/ML%2BX"
PAST_FROM = dt.date(2025, 5, 7)   # first session with a presentation topic; earlier ones were untitled socials
HEADER = "<!-- Generated by .scripts/update_mlx_events.py from today.wisc.edu (tag ML+X). Do not edit by hand. -->\n"

# The calendar re-dates a past event to the current year when its title is edited and
# refuses the original date back. Real dates for those events, by calendar event id.
DATE_OVERRIDES = {
    "214248": "2025-10-08",   # Forecasting Climate Related Conflict (calendar says 2026-10-08)
    "214961": "2025-11-05",   # Protein Engineering with MaveDB (calendar says 2026-11-05)
}


def fetch(tag, start, end):
    events, page = [], 1
    while page <= 20:
        q = urllib.parse.urlencode({"start": start, "end": end, "page": page})
        url = API.format(tag=urllib.parse.quote(tag, safe="")) + "?" + q
        req = urllib.request.Request(url, headers={"User-Agent": "ML-X-Nexus-events"})
        with urllib.request.urlopen(req, timeout=30) as r:
            data = json.load(r)
        if isinstance(data, dict):
            data = data.get("data") or data.get("events") or []
        if not data:
            break
        events.extend(data)
        page += 1
    return events


def parse_start(s):
    """The calendar returns dates like '2024/05/15 09:00:00 -0500'; accept that and ISO forms."""
    s = (s or "").strip().replace("/", "-")
    for fmt in ("%Y-%m-%d %H:%M:%S %z", "%Y-%m-%dT%H:%M:%S %z", "%Y-%m-%dT%H:%M:%S%z",
                "%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d"):
        try:
            return dt.datetime.strptime(s, fmt).replace(tzinfo=None)   # wall time in Madison; offsets dropped
        except ValueError:
            pass
    return dt.datetime.fromisoformat(s[:10])


def session_name(title):
    t = re.sub(r"^\s*ML\s*\+\s*Coffee\s*(Social)?\s*[:—–-]?\s*", "", title, flags=re.I).strip()
    return t or "ML+Coffee"


def render(events, today):
    coffee = []
    seen = set()
    for e in events:
        title = e.get("title", "")
        key = e.get("id") or (title, e.get("startDate"))
        if not re.search(r"ML\s*\+\s*Coffee", title, re.I) or key in seen:
            continue
        seen.add(key)
        try:
            start = parse_start(e.get("startDate"))
            if str(e.get("id")) in DATE_OVERRIDES:
                start = dt.datetime.combine(dt.date.fromisoformat(DATE_OVERRIDES[str(e.get("id"))]), start.time())
        except ValueError:
            print(f"skip: unreadable date {e.get('startDate')!r} on {title!r}")
            continue
        link = f"https://today.wisc.edu/events/view/{e['id']}" if e.get("id") else TAG_PAGE
        coffee.append((start, session_name(title), link))
    coffee.sort(key=lambda x: x[0])
    upcoming = [c for c in coffee if c[0].date() >= today]
    past = [c for c in coffee if PAST_FROM <= c[0].date() < today][::-1]
    out = [HEADER]
    if upcoming:
        s, name, link = upcoming[0]
        when = s.strftime("%A, %B %-d, %Y")
        if s.hour or s.minute:
            when += s.strftime(", %-I:%M %p").replace(":00", "")
        out.append(f"**Next ML+Coffee:** {when}. [{name}]({link}).\n")
    else:
        out.append("**Next ML+Coffee:** not yet scheduled. Join the [Google group](https://groups.google.com/a/g-groups.wisc.edu/g/ml-community-of-practice) to get the calendar invite.\n")
    if past:
        out.append("\n| Date | Past sessions |\n|---|---|\n")
        out += [f"| {s:%Y-%m-%d} | [{name}]({link}) |\n" for s, name, link in past]
    return "".join(out)


def main():
    today = dt.date.today()
    if "--from-file" in sys.argv:
        events = json.load(open(sys.argv[sys.argv.index("--from-file") + 1]))
    else:
        try:
            events = fetch(TAG, "2022-01-01", (today + dt.timedelta(days=365)).isoformat())
        except Exception as e:  # network or API trouble: keep the existing file
            print(f"SKIP: could not read today.wisc.edu ({e})")
            return
    text = render(events, today)
    try:
        old = open(OUT, encoding="utf-8").read()
    except FileNotFoundError:
        old = None
    if text == old:
        print(f"OK    {OUT} unchanged ({len(events)} ML+X events read)")
        return
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"WROTE {OUT} ({len(events)} ML+X events read)")


if __name__ == "__main__":
    main()
